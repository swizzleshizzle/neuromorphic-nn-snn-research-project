"""Generate the report's Appendix A, the experiment index, from the experiment folders.

The index is GENERATED, never hand-written, so it cannot drift from the record. One row per
numbered folder under `experiments/`, then any unnumbered folder (such as `probe_reanalysis`,
which is deliberately not an experiment). The title is the first `# ` heading of the folder's
committed results file, `RESULTS.md` or the older lowercase `results.md`, with its `EXP-NNN
Results -` prefix removed. A folder with neither file gets "no committed record": Phase 0 and 1
learning exercises predate the 2026-07-13 rule that every experiment commits one.

There is deliberately no verdict column. Results files are free-form, and a verdict parsed from
prose would be a guess; the title line is what each file says about itself.

The table lives in `docs/writeup/report.md` between the two marker comments below. `--write`
replaces it in place; `--check` exits non-zero if the committed table is stale.

Usage:
    .venv/bin/python -u scripts/experiment_index.py            # print the table
    .venv/bin/python -u scripts/experiment_index.py --write    # update the report
    .venv/bin/python -u scripts/experiment_index.py --check    # fail if the report is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
EXPERIMENTS = REPO / "experiments"
REPORT = REPO / "docs" / "writeup" / "report.md"

START = "<!-- experiment-index:start (generated by scripts/experiment_index.py; do not edit) -->"
END = "<!-- experiment-index:end -->"

# "EXP-062 results - ", "EXP-027 Results <long dash> ", "EXP-011 <long dash> ", "EXP-041 - "
_PREFIX = re.compile(r"^EXP-\d+(?:\s+results)?\s*[-\u2014\u2013:]\s*", re.IGNORECASE)
_NUMBERED = re.compile(r"^(\d{3})_")


def results_file(folder: Path) -> Path | None:
    # Exact-case lookups, deliberately: on a case-insensitive filesystem `folder / "RESULTS.md"`
    # would also find `results.md`, and the published path must be the file's real name.
    names = {p.name for p in folder.iterdir() if p.is_file()}
    for name in ("RESULTS.md", "results.md"):
        if name in names:
            return folder / name
    return None


def title_of(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            title = _PREFIX.sub("", line[2:].strip())
            # The report forbids long dashes; normalise any left inside a title.
            title = title.replace("\u2014", "-").replace("\u2013", "-")
            return title.replace("|", "\\|")
    return "(results file has no title line)"


def rows() -> list[tuple[str, str, str, str]]:
    numbered, other = [], []
    for folder in sorted(p for p in EXPERIMENTS.iterdir() if p.is_dir()):
        if folder.name.startswith((".", "_")):
            continue
        m = _NUMBERED.match(folder.name)
        rec = results_file(folder)
        exp_id = f"EXP-{m.group(1)}" if m else "unnumbered"
        if rec is None:
            # An unnumbered folder without a results file has nothing to index.
            if not m:
                continue
            record, title = "none", "no committed record"
        else:
            record = f"`{rec.relative_to(REPO).as_posix()}`"
            title = title_of(rec)
        (numbered if m else other).append((exp_id, f"`{folder.name}`", record, title))
    return numbered + other


def table() -> str:
    body = rows()
    n_numbered = sum(1 for r in body if r[0] != "unnumbered")
    n_record = sum(1 for r in body if r[0] != "unnumbered" and r[2] != "none")
    lines = [
        f"{n_numbered} numbered folders, {n_record} with a committed results file.",
        "",
        "| id | folder | results file | title |",
        "|---|---|---|---|",
    ]
    lines += [f"| {a} | {b} | {c} | {d} |" for a, b, c, d in body]
    return "\n".join(lines)


def splice(report: str, generated: str) -> str:
    if report.count(START) != 1 or report.count(END) != 1:
        raise SystemExit(f"{REPORT}: expected exactly one start and one end marker")
    head, rest = report.split(START)
    _, tail = rest.split(END)
    return f"{head}{START}\n{generated}\n{END}{tail}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="update the table in the report")
    mode.add_argument("--check", action="store_true", help="exit 1 if the report's table is stale")
    args = ap.parse_args()

    generated = table()
    if not (args.write or args.check):
        print(generated)
        return 0

    current = REPORT.read_text(encoding="utf-8")
    updated = splice(current, generated)
    if args.check:
        if updated != current:
            print(f"STALE: {REPORT.relative_to(REPO)} does not match the experiment folders")
            return 1
        print("OK: the experiment index matches the experiment folders")
        return 0
    REPORT.write_text(updated, encoding="utf-8")
    print(f"wrote {REPORT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
